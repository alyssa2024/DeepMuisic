import numpy as np
import torch
from torch.utils.data import Dataset

from synthesis_dataset import (
    generate_complex_harmonic_displacement,
    generate_one_btt_sequence,
    sample_amplitude_uniform,
    sample_frequency_uniform,
    simulate_fluctuating_speed_btt,
)


def build_btt_point_features(
    x_observed,
    t_samples,
    rev_ids,
    probe_ids,
    theta_samples,
    freqs_at_samples,
    base_freq,
    n_revs,
):
    """
    Build BTT token features.

    Returns:
        features:  float32 array, shape [N, 6]
        t_samples: float32 array, shape [N]
        rev_ids:   int64 array, shape [N]
        probe_ids: int64 array, shape [N]
    """

    x_real = np.real(x_observed)
    x_imag = np.imag(x_observed)

    sin_theta = np.sin(theta_samples)
    cos_theta = np.cos(theta_samples)

    rev_norm = rev_ids / max(n_revs - 1, 1)
    speed_norm = freqs_at_samples / base_freq

    features = np.stack(
        [
            x_real,
            x_imag,
            sin_theta,
            cos_theta,
            rev_norm,
            speed_norm,
        ],
        axis=-1,
    ).astype(np.float32)

    return (
        features,
        t_samples.astype(np.float32),
        rev_ids.astype(np.int64),
        probe_ids.astype(np.int64),
    )


class BTTSequenceDataset(Dataset):
    """
    Independent short BTT sequences generated by sampling physical parameters.
    """

    def __init__(
        self,
        num_sequences,
        num_cycles,
        num_probes,
        base_freq,
        fluctuation_delta,
        probe_angles,
        freq_lower,
        freq_upper,
        amp_real_center,
        amp_imag_center,
        amp_relative_half_band,
        amp_min_half_band,
        snr_db,
        seed=0,
        normalization="per_sequence_std",
    ):
        self.num_sequences = int(num_sequences)
        self.num_cycles = int(num_cycles)
        self.num_probes = int(num_probes)
        self.base_freq = float(base_freq)
        self.fluctuation_delta = float(fluctuation_delta)
        self.probe_angles = probe_angles
        self.freq_lower = np.asarray(freq_lower, dtype=np.float64)
        self.freq_upper = np.asarray(freq_upper, dtype=np.float64)
        self.amp_real_center = np.asarray(amp_real_center, dtype=np.float64)
        self.amp_imag_center = np.asarray(amp_imag_center, dtype=np.float64)
        self.amp_relative_half_band = float(amp_relative_half_band)
        self.amp_min_half_band = float(amp_min_half_band)
        self.snr_db = snr_db
        self.seed = int(seed)
        self.normalization = normalization

        if self.freq_lower.shape != self.freq_upper.shape:
            raise ValueError("freq_lower and freq_upper must have the same shape")
        if self.amp_real_center.shape != self.freq_lower.shape:
            raise ValueError("amp_real_center must match frequency shape")
        if self.amp_imag_center.shape != self.freq_lower.shape:
            raise ValueError("amp_imag_center must match frequency shape")

    def __len__(self):
        return self.num_sequences

    def __getitem__(self, idx):
        rng = np.random.default_rng(self.seed + int(idx))

        freq_hz = sample_frequency_uniform(
            self.freq_lower,
            self.freq_upper,
            rng,
        )
        amp_real, amp_imag = sample_amplitude_uniform(
            amp_real_center=self.amp_real_center,
            amp_imag_center=self.amp_imag_center,
            relative_half_band=self.amp_relative_half_band,
            min_half_band=self.amp_min_half_band,
            rng=rng,
        )

        sample = generate_one_btt_sequence(
            num_cycles=self.num_cycles,
            base_freq=self.base_freq,
            fluctuation_delta=self.fluctuation_delta,
            probe_angles=self.probe_angles,
            freq_hz=freq_hz,
            amp_real=amp_real,
            amp_imag=amp_imag,
            snr_db=self.snr_db,
            rng=rng,
        )

        x_observed = sample["x_observed"]
        if self.normalization == "per_sequence_std":
            amp_scale = float(np.std(x_observed))
            x_observed_norm = x_observed / (amp_scale + 1e-12)
        elif self.normalization in (None, "none"):
            amp_scale = 1.0
            x_observed_norm = x_observed
        else:
            raise ValueError(f"Unsupported normalization={self.normalization}")
        noise_var_norm = float(sample["noise_power"]) / ((amp_scale + 1e-12) ** 2)

        features, t_samples, rev_ids, probe_ids = build_btt_point_features(
            x_observed=x_observed_norm,
            t_samples=sample["t_samples"],
            rev_ids=sample["rev_ids"],
            probe_ids=sample["probe_ids"],
            theta_samples=sample["theta_samples"],
            freqs_at_samples=sample["freqs_at_samples"],
            base_freq=self.base_freq,
            n_revs=self.num_cycles,
        )

        target = features[:, :2]

        return {
            "x": torch.as_tensor(features, dtype=torch.float32),
            "t": torch.as_tensor(t_samples, dtype=torch.float32),
            "probe_ids": torch.as_tensor(probe_ids, dtype=torch.long),
            "rev_ids": torch.as_tensor(rev_ids, dtype=torch.long),
            "target": torch.as_tensor(target, dtype=torch.float32),
            "true_freq_hz": torch.as_tensor(freq_hz, dtype=torch.float32),
            "true_amp_real": torch.as_tensor(amp_real, dtype=torch.float32),
            "true_amp_imag": torch.as_tensor(amp_imag, dtype=torch.float32),
            "amp_scale": torch.as_tensor(amp_scale, dtype=torch.float32),
            "noise_var_norm": torch.as_tensor(noise_var_norm, dtype=torch.float32),
        }


class BTTProfileGroupDataset(Dataset):
    """
    Patch groups with shared frequencies and patch-local complex amplitudes.

    Each item is one global parameter group. The group samples one frequency
    vector, then generates multiple independent BTT patches with independent
    complex amplitudes. This matches the frequency profile-ELBO setting:
    global/shared f, patch-local nuisance c.
    """

    def __init__(
        self,
        num_groups,
        patches_per_group,
        num_cycles,
        num_probes,
        base_freq,
        fluctuation_delta,
        probe_angles,
        freq_lower,
        freq_upper,
        amp_real_center,
        amp_imag_center,
        amp_relative_half_band,
        amp_min_half_band,
        snr_db,
        seed=0,
        normalization="per_patch_std",
    ):
        self.num_groups = int(num_groups)
        self.patches_per_group = int(patches_per_group)
        self.num_cycles = int(num_cycles)
        self.num_probes = int(num_probes)
        self.base_freq = float(base_freq)
        self.fluctuation_delta = float(fluctuation_delta)
        self.probe_angles = probe_angles
        self.freq_lower = np.asarray(freq_lower, dtype=np.float64)
        self.freq_upper = np.asarray(freq_upper, dtype=np.float64)
        self.amp_real_center = np.asarray(amp_real_center, dtype=np.float64)
        self.amp_imag_center = np.asarray(amp_imag_center, dtype=np.float64)
        self.amp_relative_half_band = float(amp_relative_half_band)
        self.amp_min_half_band = float(amp_min_half_band)
        self.snr_db = snr_db
        self.seed = int(seed)
        self.normalization = normalization

        if self.num_groups <= 0:
            raise ValueError("num_groups must be positive")
        if self.patches_per_group <= 0:
            raise ValueError("patches_per_group must be positive")
        if self.freq_lower.shape != self.freq_upper.shape:
            raise ValueError("freq_lower and freq_upper must have the same shape")
        if self.amp_real_center.shape != self.freq_lower.shape:
            raise ValueError("amp_real_center must match frequency shape")
        if self.amp_imag_center.shape != self.freq_lower.shape:
            raise ValueError("amp_imag_center must match frequency shape")

    def __len__(self):
        return self.num_groups

    def _generate_patch(self, rng, freq_hz):
        amp_real, amp_imag = sample_amplitude_uniform(
            amp_real_center=self.amp_real_center,
            amp_imag_center=self.amp_imag_center,
            relative_half_band=self.amp_relative_half_band,
            min_half_band=self.amp_min_half_band,
            rng=rng,
        )
        sample = generate_one_btt_sequence(
            num_cycles=self.num_cycles,
            base_freq=self.base_freq,
            fluctuation_delta=self.fluctuation_delta,
            probe_angles=self.probe_angles,
            freq_hz=freq_hz,
            amp_real=amp_real,
            amp_imag=amp_imag,
            snr_db=self.snr_db,
            rng=rng,
        )
        return sample, amp_real, amp_imag

    def __getitem__(self, idx):
        rng = np.random.default_rng(self.seed + int(idx))
        freq_hz = sample_frequency_uniform(
            self.freq_lower,
            self.freq_upper,
            rng,
        )

        patch_samples = []
        amp_real_list = []
        amp_imag_list = []
        x_observed_list = []
        for _ in range(self.patches_per_group):
            sample, amp_real, amp_imag = self._generate_patch(rng, freq_hz)
            patch_samples.append(sample)
            amp_real_list.append(amp_real)
            amp_imag_list.append(amp_imag)
            x_observed_list.append(sample["x_observed"])

        if self.normalization in ("per_sequence_std", "per_patch_std"):
            amp_scales = np.asarray(
                [float(np.std(x_observed)) for x_observed in x_observed_list],
                dtype=np.float64,
            )
        elif self.normalization == "group_std":
            group_scale = float(np.std(np.concatenate(x_observed_list)))
            amp_scales = np.full(self.patches_per_group, group_scale, dtype=np.float64)
        elif self.normalization in (None, "none"):
            amp_scales = np.ones(self.patches_per_group, dtype=np.float64)
        else:
            raise ValueError(f"Unsupported normalization={self.normalization}")
        amp_scales = np.maximum(amp_scales, 1e-12)

        x_group = []
        t_group = []
        rev_group = []
        probe_group = []
        target_group = []
        noise_var_norm = []
        for sample, amp_scale in zip(patch_samples, amp_scales):
            x_observed_norm = sample["x_observed"] / amp_scale
            features, t_samples, rev_ids, probe_ids = build_btt_point_features(
                x_observed=x_observed_norm,
                t_samples=sample["t_samples"],
                rev_ids=sample["rev_ids"],
                probe_ids=sample["probe_ids"],
                theta_samples=sample["theta_samples"],
                freqs_at_samples=sample["freqs_at_samples"],
                base_freq=self.base_freq,
                n_revs=self.num_cycles,
            )
            x_group.append(features)
            t_group.append(t_samples)
            rev_group.append(rev_ids)
            probe_group.append(probe_ids)
            target_group.append(features[:, :2])
            noise_var_norm.append(float(sample["noise_power"]) / (amp_scale ** 2))

        return {
            "x": torch.as_tensor(np.stack(x_group, axis=0), dtype=torch.float32),
            "t": torch.as_tensor(np.stack(t_group, axis=0), dtype=torch.float32),
            "probe_ids": torch.as_tensor(
                np.stack(probe_group, axis=0),
                dtype=torch.long,
            ),
            "rev_ids": torch.as_tensor(np.stack(rev_group, axis=0), dtype=torch.long),
            "target": torch.as_tensor(
                np.stack(target_group, axis=0),
                dtype=torch.float32,
            ),
            "true_freq_hz": torch.as_tensor(freq_hz, dtype=torch.float32),
            "true_amp_real": torch.as_tensor(
                np.stack(amp_real_list, axis=0),
                dtype=torch.float32,
            ),
            "true_amp_imag": torch.as_tensor(
                np.stack(amp_imag_list, axis=0),
                dtype=torch.float32,
            ),
            "amp_scale": torch.as_tensor(amp_scales, dtype=torch.float32),
            "noise_var_norm": torch.as_tensor(noise_var_norm, dtype=torch.float32),
        }


class BTTSingleInstanceDataset(Dataset):
    """
    A single fixed-parameter long BTT sequence split into non-overlapping patches.

    The whole dataset has exactly one frequency vector and one physical complex
    amplitude vector. Train/validation/test splits are different time patches
    from the same continuous sequence, not different parameter draws.
    """

    def __init__(
        self,
        patch_num_cycles,
        num_probes,
        base_freq,
        fluctuation_delta,
        probe_angles,
        freq_lower,
        freq_upper,
        true_freq_hz,
        true_amp_real,
        true_amp_imag,
        snr_db,
        seed=0,
        num_total_patches=None,
        train_fraction=0.6,
        val_fraction=0.2,
        test_fraction=0.2,
        num_train_patches=None,
        num_val_patches=None,
        num_test_patches=None,
        patch_hop_cycles=None,
        patch_num_samples=None,
        patch_hop_samples=None,
        allow_patch_overlap=False,
        normalization="group_std",
        parameter_source="fixed",
    ):
        self.patch_num_cycles = int(patch_num_cycles)
        if num_total_patches is None:
            if (
                num_train_patches is None
                or num_val_patches is None
                or num_test_patches is None
            ):
                raise ValueError(
                    "Either num_total_patches or all explicit split patch counts "
                    "must be provided"
                )
            self.num_train_patches = int(num_train_patches)
            self.num_val_patches = int(num_val_patches)
            self.num_test_patches = int(num_test_patches)
            self.total_patches = (
                self.num_train_patches
                + self.num_val_patches
                + self.num_test_patches
            )
        else:
            self.total_patches = int(num_total_patches)
            self.num_train_patches, self.num_val_patches, self.num_test_patches = (
                self._resolve_split_counts(
                    total_patches=self.total_patches,
                    train_fraction=train_fraction,
                    val_fraction=val_fraction,
                    test_fraction=test_fraction,
                )
            )
        self.num_probes = int(num_probes)
        self.base_freq = float(base_freq)
        self.fluctuation_delta = float(fluctuation_delta)
        self.probe_angles = probe_angles
        self.freq_lower = np.asarray(freq_lower, dtype=np.float64)
        self.freq_upper = np.asarray(freq_upper, dtype=np.float64)
        self.snr_db = snr_db
        self.seed = int(seed)
        self.normalization = normalization
        self.parameter_source = parameter_source
        self.patch_hop_cycles = (
            self.patch_num_cycles
            if patch_hop_cycles is None
            else int(patch_hop_cycles)
        )
        self.patch_num_samples = (
            None if patch_num_samples is None else int(patch_num_samples)
        )
        self.patch_hop_samples = (
            self.patch_num_samples
            if patch_hop_samples is None
            else int(patch_hop_samples)
        )
        self.allow_patch_overlap = bool(allow_patch_overlap)

        if self.patch_num_cycles <= 0:
            raise ValueError("patch_num_cycles must be positive")
        if self.total_patches <= 0:
            raise ValueError("at least one patch is required")
        if self.patch_hop_cycles <= 0:
            raise ValueError("patch_hop_cycles must be positive")
        if self.patch_num_samples is not None:
            if self.patch_num_samples <= 0:
                raise ValueError("patch_num_samples must be positive")
            if self.patch_hop_samples <= 0:
                raise ValueError("patch_hop_samples must be positive")
            if (
                not self.allow_patch_overlap
                and self.patch_hop_samples < self.patch_num_samples
            ):
                raise ValueError(
                    "patch_hop_samples must be >= patch_num_samples "
                    "when overlap is disabled"
                )
        else:
            if (
                not self.allow_patch_overlap
                and self.patch_hop_cycles < self.patch_num_cycles
            ):
                raise ValueError(
                    "patch_hop_cycles must be >= patch_num_cycles "
                    "when overlap is disabled"
                )

        rng = np.random.default_rng(self.seed)
        if parameter_source == "fixed":
            freq_hz = np.asarray(true_freq_hz, dtype=np.float64)
        elif parameter_source == "sample_once":
            freq_hz = sample_frequency_uniform(self.freq_lower, self.freq_upper, rng)
        else:
            raise ValueError(
                "single_instance_parameter_source must be 'fixed' or 'sample_once'"
            )
        amp_real = np.asarray(true_amp_real, dtype=np.float64)
        amp_imag = np.asarray(true_amp_imag, dtype=np.float64)

        if freq_hz.shape != self.freq_lower.shape:
            raise ValueError("true_freq_hz must match frequency support shape")
        if amp_real.shape != freq_hz.shape or amp_imag.shape != freq_hz.shape:
            raise ValueError("true_amp_real/imag must match true_freq_hz shape")

        self.true_freq_hz = freq_hz
        self.true_amp_real = amp_real
        self.true_amp_imag = amp_imag

        if self.patch_num_samples is None:
            patch_len = self.patch_num_cycles * self.num_probes
            hop_len = self.patch_hop_cycles * self.num_probes
            total_cycles = self.patch_num_cycles + (
                self.total_patches - 1
            ) * self.patch_hop_cycles
        else:
            patch_len = self.patch_num_samples
            hop_len = self.patch_hop_samples
            total_samples = patch_len + (self.total_patches - 1) * hop_len
            total_cycles = int(np.ceil(total_samples / float(self.num_probes)))
        (
            t_samples,
            _freqs_per_rev,
            rev_ids,
            probe_ids,
            theta_samples,
            freqs_at_samples,
        ) = simulate_fluctuating_speed_btt(
            n_revs=total_cycles,
            base_freq_x=self.base_freq,
            delta=self.fluctuation_delta,
            probe_angles=self.probe_angles,
            rng=rng,
        )
        x_observed, _x_clean, noise_power = generate_complex_harmonic_displacement(
            t=t_samples,
            freqs=freq_hz,
            amp_real=amp_real,
            amp_imag=amp_imag,
            snr_db=snr_db,
            rng=rng,
        )

        patches = []
        for patch_idx in range(self.total_patches):
            start = patch_idx * hop_len
            end = start + patch_len
            if end > len(t_samples):
                raise RuntimeError("internal patch slicing exceeded long sequence")
            patches.append(
                {
                    "x_observed": x_observed[start:end],
                    "t_abs": t_samples[start:end],
                    "rev_ids": rev_ids[start:end],
                    "probe_ids": probe_ids[start:end],
                    "theta_samples": theta_samples[start:end],
                    "freqs_at_samples": freqs_at_samples[start:end],
                }
            )

        train_patches = patches[: self.num_train_patches]
        if normalization == "group_std":
            train_values = np.concatenate([p["x_observed"] for p in train_patches])
            amp_scale_group = float(np.std(train_values))
            patch_scales = np.full(self.total_patches, amp_scale_group, dtype=np.float64)
        elif normalization == "per_patch_std":
            patch_scales = np.asarray(
                [float(np.std(p["x_observed"])) for p in patches],
                dtype=np.float64,
            )
        elif normalization in (None, "none"):
            patch_scales = np.ones(self.total_patches, dtype=np.float64)
        else:
            raise ValueError(f"Unsupported normalization={normalization}")
        patch_scales = np.maximum(patch_scales, 1e-12)
        self.normalization_scale = float(patch_scales[0]) if normalization == "group_std" else None

        encoded_patches = [
            self._encode_patch(patch, patch_scales[i], noise_power)
            for i, patch in enumerate(patches)
        ]
        self._splits = {
            "train": self._stack_split(encoded_patches[: self.num_train_patches]),
            "val": self._stack_split(
                encoded_patches[
                    self.num_train_patches : self.num_train_patches
                    + self.num_val_patches
                ]
            ),
            "test": self._stack_split(encoded_patches[-self.num_test_patches :]),
        }

    def __len__(self):
        return 1

    @staticmethod
    def _resolve_split_counts(
        total_patches,
        train_fraction,
        val_fraction,
        test_fraction,
    ):
        total_patches = int(total_patches)
        if total_patches < 3:
            raise ValueError("num_total_patches must be at least 3")
        fractions = np.asarray(
            [train_fraction, val_fraction, test_fraction],
            dtype=np.float64,
        )
        if np.any(fractions <= 0):
            raise ValueError("train/val/test fractions must be positive")
        fractions = fractions / fractions.sum()
        raw = fractions * total_patches
        counts = np.floor(raw).astype(np.int64)
        counts = np.maximum(counts, 1)
        while counts.sum() > total_patches:
            idx = int(np.argmax(counts))
            if counts[idx] <= 1:
                raise ValueError("Cannot allocate at least one patch per split")
            counts[idx] -= 1
        remainders = raw - np.floor(raw)
        for idx in np.argsort(-remainders):
            if counts.sum() >= total_patches:
                break
            counts[int(idx)] += 1
        return tuple(int(x) for x in counts)

    def _encode_patch(self, patch, amp_scale, noise_power):
        x_norm = patch["x_observed"] / amp_scale
        rev_ids_local = patch["rev_ids"] - patch["rev_ids"][0]
        local_n_revs = max(int(rev_ids_local.max()) + 1, 1)
        features, t_samples, rev_ids, probe_ids = build_btt_point_features(
            x_observed=x_norm,
            t_samples=patch["t_abs"],
            rev_ids=rev_ids_local,
            probe_ids=patch["probe_ids"],
            theta_samples=patch["theta_samples"],
            freqs_at_samples=patch["freqs_at_samples"],
            base_freq=self.base_freq,
            n_revs=local_n_revs,
        )
        t_abs = t_samples.astype(np.float32)
        t_local = (t_abs - t_abs[0]).astype(np.float32)
        return {
            "x": features,
            "t_abs": t_abs,
            "t_local": t_local,
            "probe_ids": probe_ids,
            "rev_ids": rev_ids,
            "target": features[:, :2],
            "amp_scale": np.float32(amp_scale),
            "noise_var_norm": np.float32(float(noise_power) / (amp_scale ** 2)),
            "patch_t0_abs": np.float32(t_abs[0]),
        }

    @staticmethod
    def _stack_split(patches):
        if not patches:
            raise ValueError("split must contain at least one patch")
        keys = patches[0].keys()
        stacked = {}
        for key in keys:
            dtype = torch.long if key in ("probe_ids", "rev_ids") else torch.float32
            stacked[key] = torch.as_tensor(
                np.stack([patch[key] for patch in patches], axis=0),
                dtype=dtype,
            )
        return stacked

    def __getitem__(self, idx):
        if int(idx) != 0:
            raise IndexError("BTTSingleInstanceDataset contains exactly one item")
        return {
            "train": self._splits["train"],
            "val": self._splits["val"],
            "test": self._splits["test"],
            "true_freq_hz": torch.as_tensor(self.true_freq_hz, dtype=torch.float32),
            "true_amp_real": torch.as_tensor(self.true_amp_real, dtype=torch.float32),
            "true_amp_imag": torch.as_tensor(self.true_amp_imag, dtype=torch.float32),
            "normalization_scale": torch.as_tensor(
                1.0 if self.normalization_scale is None else self.normalization_scale,
                dtype=torch.float32,
            ),
            "total_train_patches": torch.as_tensor(
                self.num_train_patches,
                dtype=torch.long,
            ),
        }
